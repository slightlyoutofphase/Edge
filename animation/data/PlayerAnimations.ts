function climbingPose(frontUp: boolean) {
  const pose: BonePose = {
    ...guardPose(),
    ...bracePose(0, 0),
    torso: { rotate: 4 },
    head: { rotate: -10 },
    weapon: { scale: { x: 0, y: 0 } },
  };
  placeHand(pose, "front", { x: 5, y: frontUp ? -54 : -38 });
  placeHand(pose, "back", { x: -5, y: frontUp ? -38 : -54 });
  pose[frontUp ? "leg-front-upper" : "leg-back-upper"] = { rotate: -55 };
  pose[frontUp ? "leg-front-lower" : "leg-back-lower"] = { rotate: 88 };
  pose[frontUp ? "leg-back-upper" : "leg-front-upper"] = { rotate: -10 };
  pose[frontUp ? "leg-back-lower" : "leg-front-lower"] = { rotate: 24 };
  return pose;
}
